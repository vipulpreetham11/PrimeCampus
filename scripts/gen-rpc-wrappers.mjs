// Generates src/lib/rpc/functions.ts — one typed wrapper per browser-callable RPC — from
// src/generated/database.types.ts. Run `npm run gen:rpc` after regenerating database types.
//   * functions taking p_ctx_rev  -> schoolRpc (revision injected from the context store)
//   * all other functions         -> callRpc
//   * svc_* (service_role only)   -> skipped: browsers can never execute them
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const typesPath = path.join(root, 'src/generated/database.types.ts');
const outPath = path.join(root, 'src/lib/rpc/functions.ts');

const src = readFileSync(typesPath, 'utf8');
const fnBlockStart = src.indexOf('    Functions: {');
const fnBlockEnd = src.indexOf('    Enums: {', fnBlockStart);
if (fnBlockStart < 0 || fnBlockEnd < 0) throw new Error('Could not find Functions block in database types');
const block = src.slice(fnBlockStart, fnBlockEnd);

// Each function starts at 6-space indentation: `      name: {`
const entries = [];
const re = /^ {6}([a-z_0-9]+): \{([\s\S]*?)(?=^ {6}[a-z_0-9]+: \{|^ {4}\})/gm;
let m;
while ((m = re.exec(block))) {
  const [, name, body] = m;
  const argsMatch = /Args:\s*(never|\{[\s\S]*?\})\s*[\n;]?\s*Returns/.exec(body);
  if (!argsMatch) throw new Error(`Could not parse Args of ${name}`);
  const argsText = argsMatch[1];
  const noArgs = argsText === 'never';
  const props = noArgs
    ? []
    : [...argsText.matchAll(/(p_[a-z_0-9]*|p)(\??):/g)].map((x) => ({ name: x[1], optional: x[2] === '?' }));
  entries.push({ name, noArgs, props });
}
if (entries.length < 50) throw new Error(`Parsed only ${entries.length} functions — parser out of date?`);

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const browser = entries
  .filter((e) => !e.name.startsWith('svc_'))
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  '// GENERATED by `npm run gen:rpc` (scripts/gen-rpc-wrappers.mjs) from src/generated/database.types.ts.',
  '// Do not hand-edit. One wrapper per browser-callable RPC in `public`.',
  "import { callRpc, schoolRpc, type RpcArgs, type RpcOptions, type SchoolArgs } from './client';",
  '',
];
const school = [];
const plain = [];
for (const e of browser) {
  const fn = camel(e.name);
  const isSchool = e.props.some((p) => p.name === 'p_ctx_rev');
  if (e.noArgs) {
    lines.push(`export const ${fn} = (options?: RpcOptions) => callRpc('${e.name}', undefined, options);`);
    plain.push(e.name);
  } else if (isSchool) {
    const rest = e.props.filter((p) => p.name !== 'p_ctx_rev');
    const optional = rest.every((p) => p.optional);
    const param = optional ? `args: SchoolArgs<'${e.name}'> = {}` : `args: SchoolArgs<'${e.name}'>`;
    lines.push(
      `export const ${fn} = (${param}, options?: RpcOptions) => schoolRpc('${e.name}', args, options);`,
    );
    school.push(e.name);
  } else {
    const optional = e.props.every((p) => p.optional);
    const param = optional ? `args: RpcArgs<'${e.name}'> = {}` : `args: RpcArgs<'${e.name}'>`;
    lines.push(
      `export const ${fn} = (${param}, options?: RpcOptions) => callRpc('${e.name}', args, options);`,
    );
    plain.push(e.name);
  }
}
lines.push('');
lines.push(`/** RPCs that take p_ctx_rev (${school.length}). */`);
lines.push(`export const SCHOOL_RPCS = ${JSON.stringify(school)} as const;`);
lines.push(`/** Browser RPCs without a context revision (${plain.length}). */`);
lines.push(`export const CONTEXTLESS_RPCS = ${JSON.stringify(plain)} as const;`);
lines.push('');
writeFileSync(outPath, lines.join('\n'));
console.log(
  `Wrote ${browser.length} wrappers (${school.length} school, ${plain.length} context-free) to ${path.relative(root, outPath)}`,
);
